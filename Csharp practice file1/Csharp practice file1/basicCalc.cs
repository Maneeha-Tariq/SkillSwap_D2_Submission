using System;

class basicCalc
{
    internal  int add(int a, int b)
    {
        return a + b;
    }
    internal  int sub(int a, int b)
    {
        return a - b;
    }
   internal int mul(int a, int b)
    {
        return a * b;
    }
   internal int div(int a, int b)
    {
        return a / b;
    }
}
